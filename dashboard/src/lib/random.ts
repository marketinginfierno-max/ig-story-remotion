// PRNG determinista con semilla: mismo string de entrada -> siempre la misma
// secuencia de "aleatorios". Se usa para generar datos de ejemplo que son
// estables entre renders y recargas en vez de cambiar cada vez (analytics,
// competitors) — ver CLAUDE.md.

export function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (Math.imul(31, hash) + str.charCodeAt(i)) | 0;
  }
  return hash;
}

export function mulberry32(seed: number) {
  let a = seed;
  return function random() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
